insert into sales_scope select 'customer',public.convert_lead((select id from sales_scope where label='tenant'),(select id from sales_scope where label='lead'));
select is(public.convert_lead((select id from sales_scope where label='tenant'),(select id from sales_scope where label='lead')),(select id from sales_scope where label='customer'),'Repeat conversion returns same customer');
