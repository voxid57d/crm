create extension if not exists pgtap with schema extensions;
set search_path=public,extensions;
select plan(12);
select has_table('public','leads','Sales leads exist');
select is((select count(*)::int from pg_tables where schemaname='public' and rowsecurity and tablename in
 ('sales_pipelines','sales_stages','lead_sources','lead_loss_reasons','leads','lead_notes','lead_activities','lead_followups','sales_configuration_history')),9,'Sales tables all enforce RLS');
select ok(not has_table_privilege('authenticated','public.lead_activities','update'),'History cannot be altered directly');
select ok(not has_table_privilege('authenticated','public.sales_stages','delete'),'Stages cannot be deleted directly');
create temporary table sales_scope(label text primary key,id uuid);
grant select,insert on sales_scope to authenticated;
insert into auth.users(id,email) values('99997000-0000-0000-0000-000000000001','sales-native-a@example.test'),('99997000-0000-0000-0000-000000000002','sales-native-b@example.test');
set local role authenticated;
set local request.jwt.claim.sub='99997000-0000-0000-0000-000000000001';
insert into sales_scope select 'tenant',public.create_business('Native Sales');
insert into sales_scope select 'branch',id from public.branches limit 1;
insert into sales_scope select 'pipeline',id from public.sales_pipelines limit 1;
insert into sales_scope select 'stage',id from public.sales_stages where outcome='open' order by position limit 1;
insert into sales_scope select 'lead',public.save_lead((select id from sales_scope where label='tenant'),null,jsonb_build_object('branch_id',(select id from sales_scope where label='branch'),'pipeline_id',(select id from sales_scope where label='pipeline'),'stage_id',(select id from sales_scope where label='stage'),'first_name','Native lead','phone','+998 90 555'));
select is((select email from public.leads limit 1),null::text,'Lead email is optional');
